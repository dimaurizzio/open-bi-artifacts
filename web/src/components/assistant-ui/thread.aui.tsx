/** Qué está haciendo el agente mientras no hay texto nuevo, con el tiempo transcurrido. */
const ThinkingStatus: FC = () => {
  const label = useAuiState((s) => {
    if (s.message.role !== "assistant" || s.message.status?.type !== "running") return "";
    const parts = s.message.content;
    const last = parts[parts.length - 1];
    if (last?.type === "text" && last.text) return "";
    if (last?.type === "tool-call") {
      return last.result === undefined
        ? toolActivity(last.toolName, (last.args ?? {}) as Record<string, unknown>)
        : "Pensando el próximo paso";
    }
    return "Pensando";
  });
  const startedAt = useAuiState((s) => s.message.createdAt?.getTime() ?? 0);
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    if (!label) return;
    const t = window.setInterval(() => setNow(Date.now()), 1000);
    return () => window.clearInterval(t);
  }, [label]);
  if (!label) return null;
  const secs = Math.max(0, Math.round((now - (startedAt || now)) / 1000));
  const elapsed = secs < 60 ? `${secs}s` : `${Math.floor(secs / 60)}m ${secs % 60}s`;
  return <ThinkingIndicator label={label} elapsed={elapsed} className="py-1.5" />;
};

/** Turno detenido con "Detener": queda lo escrito y se puede continuar. */
const StoppedNotice: FC = () => {
  const stopped = useAuiState(
    (s) =>
      s.message.isLast &&
      s.message.status?.type === "incomplete" &&
      s.message.status.reason === "cancelled",
  );
  const [dismissed, setDismissed] = useState(false);
  if (!stopped || dismissed) return null;
  return (
    <StoppedRun
      className="mt-2"
      words={[]}
      reason="Detenido"
      onContinue={() => void useAppStore.getState().send("Continuá desde donde quedaste.")}
      onDiscard={() => setDismissed(true)}
    />
  );
};

